def _lang():
    for var in ("LANGUAGE", "LC_ALL", "LC_MESSAGES", "LANG"):
        v = os.environ.get(var)
        if v:
            return v.split(":")[0].lower()
    return "en"


_lc = _lang()
_TABLE = _PT if _lc.startswith("pt") else _JA if _lc.startswith("ja") else {}


def _(s):
    return _TABLE.get(s, s)
